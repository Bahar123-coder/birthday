import { neon } from '@neondatabase/serverless';
// Provide the connection string and existing wishes through stdin only.
import { createInterface } from 'node:readline';
const reader = createInterface({input: process.stdin});
const input = await new Promise(resolve => reader.once('line', resolve));
reader.close();
try {
  const { connectionString, siteUrl, bearerToken } = JSON.parse(input);
  const existing = await fetch(siteUrl + '/api/wishes', {headers: {'OAI-Sites-Authorization': 'Bearer ' + bearerToken}});
  if (!existing.ok) throw new Error('Could not read existing wishes');
  const wishes = await existing.json();
  if (!Array.isArray(wishes)) throw new Error('Invalid existing wishes');
  const sql = neon(connectionString);
  await sql`CREATE TABLE IF NOT EXISTS birthday_wishes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 60),
    message TEXT NOT NULL CHECK (char_length(message) BETWEEN 1 AND 2000),
    emoji TEXT NOT NULL DEFAULT '💛',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    legacy_d1_id INTEGER UNIQUE
  )`;
  for (const wish of wishes) {
    await sql`INSERT INTO birthday_wishes (name, message, emoji, created_at, legacy_d1_id)
      VALUES (${wish.name}, ${wish.message}, ${wish.emoji}, ${wish.createdAt}, ${wish.id})
      ON CONFLICT (legacy_d1_id) DO NOTHING`;
  }
  const marker = 'integration-check-' + crypto.randomUUID();
  const result = await sql.transaction([
    sql`INSERT INTO birthday_wishes (name, message, emoji) VALUES (${marker}, 'Database integration verification', '💛') RETURNING id`,
    sql`SELECT name FROM birthday_wishes WHERE name = ${marker}`,
    sql`DELETE FROM birthday_wishes WHERE name = ${marker} RETURNING id`,
  ]);
  if (result[0].length !== 1 || result[1].length !== 1 || result[2].length !== 1) throw new Error('Verification failed');
  const [summary] = await sql`SELECT COUNT(*)::integer AS count FROM birthday_wishes`;
  console.log(JSON.stringify({initialized: true, migrated: wishes.length, readWriteVerified: true, wishCount: summary.count}));
} catch (error) {
  // Do not log connection strings or driver errors, which can contain credentials.
  console.error(JSON.stringify({initialized: false, errorType: error?.name || 'Error', code: error?.code || null}));
  process.exitCode = 1;
}
